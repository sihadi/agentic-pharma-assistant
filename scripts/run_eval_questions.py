"""Run the public evaluation questions (+ unseen ones) end-to-end through the agent.

Usage:  python -m scripts.run_eval_questions [--only P1,P3]

Checks for each question: expected source files cited, disclaimer present,
critic verdict / confidence, tools chosen by the agent. Writes the full
answers and a summary table to docs/EVAL_RESULTS.md (the traces go to
data/traces/<trace_id>.json).
"""

from __future__ import annotations

import argparse
import json
import time

from app.config import PROJECT_ROOT, load_settings
from app.logging_config import configure_logging
from app.runtime import build_runtime
from app.tracing import TraceStore, Tracer

QUESTIONS = [
    ("P1", "What are the main contraindications for warfarin?", ["dailymed-warfarin.md"]),
    ("P2", "Compare the contraindications of warfarin and apixaban. What conditions are shared and which "
           "are unique to each drug?", ["dailymed-warfarin.md", "dailymed-apixaban.md"]),
    ("P3", "A patient currently on warfarin is prescribed sertraline. What is the risk of bleeding and what "
           "monitoring is recommended?", ["dailymed-warfarin.md", "dailymed-sertraline.md"]),
    ("P4", "A patient with an eGFR of 25 mL/min is being considered for metformin. Is metformin "
           "contraindicated at this level of renal function, and what is the threshold?",
     ["dailymed-metformin.md"]),
    ("U1", "Can Zoloft be taken together with an MAO inhibitor?", ["dailymed-sertraline.md"]),
    ("U2", "What is the maximum daily dose of acetaminophen and what happens above it?", []),
    ("U3", "What are the contraindications of lisinopril?", []),
    ("U4", "Who won the 2022 football World Cup?", []),
]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", default="")
    args = parser.parse_args()
    only = {x.strip() for x in args.only.split(",") if x.strip()}

    settings = load_settings()
    configure_logging("WARNING")
    runtime = build_runtime(settings)
    store = TraceStore(settings.trace_dir)

    rows, sections = [], []
    for qid, question, expected in QUESTIONS:
        if only and qid not in only:
            continue
        tracer = Tracer(f"eval-{qid}-{int(time.time())}", question)
        result = runtime.agent.run(question, tracer)
        store.save(tracer)
        missing = [f for f in expected if f not in result["sources"]]
        review = result["review"]
        tools = ", ".join(sorted({t["tool"] for t in result["tools_used"]})) or "-"
        ok = not missing and "not medical advice" in result["answer"]
        rows.append(f"| {qid} | {'PASS' if ok else 'FAIL'} | {result['status']} | {review.get('verdict')} | "
                    f"{review.get('confidence')} | {', '.join(result['sources']) or '-'} | {tools} | "
                    f"{result['usage']['llm_calls']} | {result['usage']['duration_ms'] / 1000:.1f}s |")
        sections.append(f"## {qid} — {question}\n\nExpected sources: {', '.join(expected) or '(none)'}  \n"
                        f"Trace: `data/traces/{tracer.trace_id}.json`\n\n{result['answer']}\n\n"
                        f"<details><summary>Review & tools</summary>\n\n```json\n"
                        f"{json.dumps({'review': review, 'tools_used': result['tools_used'], 'plan': result['plan']}, indent=2, ensure_ascii=False)}"
                        f"\n```\n</details>\n")
        print(rows[-1], flush=True)

    out = PROJECT_ROOT / "docs" / "EVAL_RESULTS.md"
    out.write_text(
        "# End-to-end evaluation results\n\nGenerated by `python -m scripts.run_eval_questions` "
        f"(chat model `{settings.chat_model}`, embeddings `{settings.embedding_model}`).\n\n"
        "| Id | Check | Status | Verdict | Confidence | Sources cited | Tools chosen by agent | LLM calls | Time |\n"
        "|---|---|---|---|---:|---|---|---:|---:|\n" + "\n".join(rows) + "\n\n" + "\n".join(sections),
        encoding="utf-8",
    )
    print(f"Written {out}")


if __name__ == "__main__":
    main()
